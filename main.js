(() => {
  'use strict';

  const EVENT_NAME = '__YT_SRV2_MESSAGE__';
  const ORIGINAL_FETCH = window.fetch.bind(window);
  const ORIGINAL_XHR_OPEN = XMLHttpRequest.prototype.open;
  const ORIGINAL_XHR_SEND = XMLHttpRequest.prototype.send;

  let last = {
    videoId: null,
    language: null,
    autoGenerated: false,
    title: null,
    srv2: null,
    sourceUrl: null,
    capturedAt: null,
    error: null
  };

  let currentVideoId = getVideoId();

  function getVideoId() {
    try {
      const url = new URL(location.href);
      if (url.pathname !== '/watch') return null;
      return url.searchParams.get('v');
    } catch {
      return null;
    }
  }

  function getTitle() {
    return document.title
      .replace(/\s*-\s*YouTube\s*$/, '')
      .trim();
  }

  function isEnglishAutoSub(urlString) {
    try {
      const url = new URL(urlString, location.href);
      if (url.hostname !== 'www.youtube.com') return false;
      if (url.pathname !== '/api/timedtext') return false;

      const p = url.searchParams;
      const lang = p.get('lang') || p.get('languageCode') || '';
      const kind = p.get('kind') || '';
      const caps = p.get('caps') || '';
      const translation = p.get('tlang');

      if (translation) return false;
      if (kind !== 'asr' && caps !== 'asr') return false;
      return /^en(?:[-_].*)?$/i.test(lang);
    } catch {
      return false;
    }
  }

  function makeSrv2Url(urlString) {
    const url = new URL(urlString, location.href);
    url.searchParams.set('fmt', 'srv2');
    return url.toString();
  }

  function postMessage(payload) {
    window.postMessage({
      channel: EVENT_NAME,
      ...payload
    }, '*');
  }

  function resetForVideo(videoId) {
    if (videoId === currentVideoId) return;
    currentVideoId = videoId;
    last = {
      videoId,
      language: null,
      autoGenerated: false,
      title: getTitle(),
      srv2: null,
      sourceUrl: null,
      capturedAt: null,
      error: null
    };
    postMessage({ type: 'RESET', status: getStatus() });
  }

  function getStatus() {
    const videoId = getVideoId();
    if (videoId !== currentVideoId) {
      resetForVideo(videoId);
    }
    return {
      type: 'STATUS',
      status: {
        videoId: last.videoId,
        title: getTitle() || last.title || 'YouTube video',
        language: last.language,
        autoGenerated: last.autoGenerated,
        available: Boolean(last.srv2),
        capturedAt: last.capturedAt,
        error: last.error
      }
    };
  }

  async function captureSrv2(sourceUrl, requestHeaders, credentials) {
    const srv2Url = makeSrv2Url(sourceUrl);
    const headers = requestHeaders || undefined;

    try {
      const response = await ORIGINAL_FETCH(srv2Url, {
        method: 'GET',
        headers,
        credentials: credentials || 'include',
        cache: 'no-store'
      });

      if (!response.ok) {
        throw new Error(`SRV2 request failed: HTTP ${response.status}`);
      }

      const text = await response.text();
      if (!text.trim()) {
        throw new Error('SRV2 response was empty. YouTube may require a browser session token that was not included in the request.');
      }

      const normalized = normalizeToSrv2(text);
      if (!normalized) {
        throw new Error('The timedtext response could not be converted to SRV2.');
      }

      const videoId = getVideoId();
      if (!videoId) return;

      // YouTube may request caption data more than once during playback.
      // Keep the largest successful payload so a later partial request does
      // not overwrite an already captured full transcript.
      if (last.srv2 && normalized.length < last.srv2.length) return;

      last = {
        videoId,
        language: 'en',
        autoGenerated: true,
        title: getTitle(),
        srv2: normalized,
        sourceUrl,
        capturedAt: new Date().toISOString(),
        error: null
      };

      postMessage({ type: 'CAPTION', status: getStatus(), srv2: normalized });
    } catch (error) {
      last.error = error instanceof Error ? error.message : String(error);
      postMessage({ type: 'ERROR', status: getStatus() });
    }
  }

  function normalizeToSrv2(text) {
    const trimmed = text.trim();

    if (trimmed.startsWith('<')) {
      // YouTube's srv2 is XML. Keep it exactly as returned by YouTube.
      if (trimmed.includes('<text') || trimmed.includes('<transcript') || trimmed.includes('<timedtext')) {
        return trimmed.endsWith('\n') ? trimmed : `${trimmed}\n`;
      }
    }

    // Fallback for json3 responses if YouTube ignores fmt=srv2.
    try {
      const json = JSON.parse(trimmed);
      return json3ToSrv2(json);
    } catch {
      return null;
    }
  }

  function xmlEscape(value) {
    return value
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;');
  }

  function json3ToSrv2(json) {
    if (!Array.isArray(json.events)) return null;

    const lines = ['<?xml version="1.0" encoding="UTF-8"?><transcript>'];

    for (const event of json.events) {
      const segs = Array.isArray(event.segs) ? event.segs : [];
      const text = segs.map(seg => typeof seg.utf8 === 'string' ? seg.utf8 : '').join('');
      if (!text) continue;

      const start = Number(event.tStartMs || 0) / 1000;
      const duration = Number(event.dDurationMs || 0) / 1000;
      const attrs = [`start="${start.toFixed(3).replace(/0+$/, '').replace(/\.$/, '')}"`];
      if (duration > 0) {
        attrs.push(`dur="${duration.toFixed(3).replace(/0+$/, '').replace(/\.$/, '')}"`);
      }
      lines.push(`<text ${attrs.join(' ')}>${xmlEscape(text)}</text>`);
    }

    lines.push('</transcript>');
    return `${lines.join('\n')}\n`;
  }

  function inspectRequest(input, init) {
    let url = '';
    let headers;
    let credentials = 'include';

    try {
      if (input instanceof Request) {
        url = input.url;
        headers = input.headers;
        credentials = input.credentials || credentials;
      } else {
        url = String(input);
      }

      if (init?.headers) headers = new Headers(init.headers);
      if (init?.credentials) credentials = init.credentials;
    } catch {
      return;
    }

    if (!url || !isEnglishAutoSub(url)) return;

    captureSrv2(url, headers, credentials);
  }

  window.fetch = function(input, init) {
    inspectRequest(input, init);
    return ORIGINAL_FETCH(input, init);
  };

  XMLHttpRequest.prototype.open = function(method, url, ...rest) {
    this.__ytSrv2Method = method;
    this.__ytSrv2Url = String(url);
    return ORIGINAL_XHR_OPEN.call(this, method, url, ...rest);
  };

  XMLHttpRequest.prototype.send = function(body) {
    const method = String(this.__ytSrv2Method || '').toUpperCase();
    const url = this.__ytSrv2Url || '';

    if (method === 'GET' && isEnglishAutoSub(url)) {
      // XHR headers are not exposed reliably enough to clone here; the page
      // session cookies are still sent by this main-world fetch.
      captureSrv2(url, undefined, 'include');
    }

    return ORIGINAL_XHR_SEND.call(this, body);
  };

  window.addEventListener('message', event => {
    if (event.source !== window) return;
    const data = event.data;
    if (!data || data.channel !== EVENT_NAME) return;

    if (data.type === 'GET_STATUS') {
      postMessage(getStatus());
    }

    if (data.type === 'GET_CAPTION') {
      const status = getStatus();
      postMessage({
        type: 'CAPTION',
        status: status.status,
        srv2: last.srv2
      });
    }
  });

  // YouTube is a SPA. Reset the captured track as soon as the watch URL changes.
  const originalPushState = history.pushState;
  history.pushState = function(...args) {
    const result = originalPushState.apply(this, args);
    resetForVideo(getVideoId());
    return result;
  };

  const originalReplaceState = history.replaceState;
  history.replaceState = function(...args) {
    const result = originalReplaceState.apply(this, args);
    resetForVideo(getVideoId());
    return result;
  };

  window.addEventListener('popstate', () => resetForVideo(getVideoId()));
  window.addEventListener('yt-navigate-start', () => resetForVideo(getVideoId()));
  window.addEventListener('yt-navigate-finish', () => resetForVideo(getVideoId()));

  postMessage({ type: 'READY', status: getStatus().status });
})();
