(() => {
  'use strict';

  const EVENT_NAME = '__YT_SRV2_MESSAGE__';
  let status = {
    videoId: null,
    title: 'YouTube video',
    language: null,
    autoGenerated: false,
    available: false,
    capturedAt: null,
    error: null
  };
  let srv2 = null;

  function postToMain(type) {
    window.postMessage({ channel: EVENT_NAME, type }, '*');
  }

  window.addEventListener('message', event => {
    if (event.source !== window) return;
    const data = event.data;
    if (!data || data.channel !== EVENT_NAME) return;

    if (data.status) status = data.status;
    if (data.type === 'CAPTION') srv2 = data.srv2 || null;
    if (data.type === 'RESET') srv2 = null;

    if (data.type === 'CAPTION' || data.type === 'ERROR' || data.type === 'RESET' || data.type === 'READY') {
      // Popup requests are handled through the extension messaging channel.
    }
  });

  chrome.runtime.onMessage.addListener((message, _sender, sendResponse) => {
    if (!message || typeof message.type !== 'string') return;

    if (message.type === 'GET_STATUS') {
      postToMain('GET_STATUS');
      setTimeout(() => sendResponse({ status, hasData: Boolean(srv2) }), 50);
      return true;
    }

    if (message.type === 'GET_CAPTION') {
      postToMain('GET_CAPTION');
      setTimeout(() => sendResponse({ status, srv2 }), 50);
      return true;
    }
  });
})();
